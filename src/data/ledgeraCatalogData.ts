// Helper: Filter catalog items by category, query, price, frequency
export function filterLedgeraCatalog(
  category: CatalogCategoryFilter = 'All Categories',
  query: string = '',
  maxPrice?: number
): LedgeraCatalogService[] {
  return LEDGERA_200_CATALOG.filter((item) => {
    const matchesCategory = category === 'All Categories' || item.category === category;
    const qLower = query.toLowerCase().trim();
    const matchesQuery =
      !qLower ||
      item.title.toLowerCase().includes(qLower) ||
      item.code.toLowerCase().includes(qLower) ||
      item.subCategory.toLowerCase().includes(qLower) ||
      item.description.toLowerCase().includes(qLower) ||
      item.ftaRef.toLowerCase().includes(qLower) ||
      item.deliverables.some((d) => d.toLowerCase().includes(qLower));

    const matchesPrice = maxPrice === undefined || item.pricing.startingAed <= maxPrice;

    return matchesCategory && matchesQuery && matchesPrice;
  });
}
